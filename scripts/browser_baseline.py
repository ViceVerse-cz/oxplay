def sha256(path):
    with path.open("rb") as source:
        return hashlib.file_digest(source, "sha256").hexdigest()


def archive_members(archive):
    """Validate the complete archive, including symlink parents, before any write."""
    members = archive.infolist()
    if len(members) > 10000 or sum(m.file_size for m in members) > 2 * 1024**3:
        raise ValueError("archive exceeds extraction bounds")
    paths, links = set(), {}
    for member in members:
        path = PurePosixPath(member.filename)
        if (path.is_absolute() or ".." in path.parts or "\\" in member.filename
                or not path.parts or path.parts[0] != "chrome-mac-arm64"
                or path in paths):
            raise ValueError("unsafe or duplicate archive path")
        paths.add(path)
        mode = member.external_attr >> 16
        if stat.S_ISLNK(mode):
            if member.file_size > 4096:
                raise ValueError("oversized symlink")
            target = PurePosixPath(archive.read(member).decode("utf-8"))
            if target.is_absolute() or ".." in target.parts or not target.parts:
                raise ValueError("unsafe symlink target")
            links[path] = target
        elif stat.S_IFMT(mode) not in (0, stat.S_IFREG, stat.S_IFDIR):
            raise ValueError("unsupported archive special file")
    for path in paths:
        if any(parent in links for parent in path.parents):
            raise ValueError("archive member traverses symlink")
    return members, links


def extract(archive_path, destination):
    with zipfile.ZipFile(archive_path) as archive:
        members, links = archive_members(archive)
        for member in members:
            path = destination / member.filename
            if PurePosixPath(member.filename) in links:
                continue
            if member.is_dir():
                path.mkdir(parents=True, exist_ok=True)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                with archive.open(member) as source, path.open("xb") as output:
                    shutil.copyfileobj(source, output, 1024 * 1024)
                path.chmod((member.external_attr >> 16) & 0o777 or 0o644)
        for path, target in links.items():
            full = destination / str(path)
            full.parent.mkdir(parents=True, exist_ok=True)
            full.symlink_to(str(target))
        for path in links:
            (destination / str(path)).resolve(strict=True).relative_to(destination.resolve())


def verify_application(base):
    app = base / APP_REL
    strict = subprocess.run(["codesign", "--verify", "--deep", "--strict", str(app)],
                            capture_output=True, text=True, timeout=60)
    signature = subprocess.run(["codesign", "-d", "--verbose=4", str(app)],
                               check=True, capture_output=True, text=True, timeout=10).stderr
    # The actual upstream CfT package is linker-ad-hoc signed and resources are
    # unsealed. Do not pretend it has Developer ID, re-sign it, or alter Gatekeeper.
    if "Signature=adhoc" not in signature or "TeamIdentifier=not set" not in signature:
        raise ValueError("signature differs from inspected pinned artifact")
    subprocess.run(["codesign", "--verify", "--deep", "--strict", "--ignore-resources", str(app)],
                   check=True, capture_output=True, timeout=60)
    archive_path = ARTIFACTS / "chrome-mac-arm64.zip"
    if sha256(archive_path) != ARCHIVE_SHA256:
        raise ValueError("official archive differs from recorded observed digest")
    with zipfile.ZipFile(archive_path) as archive:
        members, links = archive_members(archive)
        expected_files = set()
        for member in members:
            path = base / member.filename
            if member.is_dir():
                continue
            expected_files.add(path.relative_to(base))
            if PurePosixPath(member.filename) in links:
                if not path.is_symlink() or os.readlink(path) != str(links[PurePosixPath(member.filename)]):
                    raise ValueError("framework symlink changed")
            else:
                if path.is_symlink():
                    raise ValueError("unexpected file symlink")
                with archive.open(member) as source:
                    expected = hashlib.file_digest(source, "sha256").hexdigest()
                if sha256(path) != expected:
                    raise ValueError("extracted browser differs from official archive")
        actual_files = {p.relative_to(base) for p in (base / "chrome-mac-arm64").rglob("*")
                        if p.is_symlink() or p.is_file()}
        if actual_files != expected_files:
            raise ValueError("unexpected browser bundle files")
    with (app / "Contents/Info.plist").open("rb") as source:
        info = plistlib.load(source)
    if info["CFBundleShortVersionString"] != VERSION:
        raise ValueError("unexpected browser version")
    architecture = subprocess.check_output(["lipo", "-archs", str(base / EXE_REL)],
                                           text=True, timeout=10).strip()
    if architecture != "arm64":
        raise ValueError("browser must be native ARM64")
    return {"signature": signature, "architecture": architecture,
            "strict_bundle_signature_valid": strict.returncode == 0,
            "strict_bundle_signature_diagnostic": strict.stderr.strip(),
            "code_pages_valid_ignoring_unsealed_resources": True,
            "all_archive_members_verified": True,
            "trust_limit": "Official HTTPS provenance and recorded observed digest; "
                          "ad-hoc code signatures do not authenticate a publisher; resources unsealed.",
            "executable_sha256": sha256(base / EXE_REL)}


def prepare():
    ARTIFACTS.mkdir(parents=True, exist_ok=True)
    with urllib.request.urlopen(METADATA, timeout=30) as response:
        if response.url != METADATA:
            raise ValueError("unexpected release-metadata redirect")
        metadata_bytes = response.read(2 * 1024 * 1024 + 1)
    if len(metadata_bytes) > 2 * 1024 * 1024:
        raise ValueError("oversized official metadata")
    metadata = json.loads(metadata_bytes)
    urls = [item["url"] for item in metadata["downloads"]["chrome"]
            if item["platform"] == "mac-arm64"]
    if metadata["version"] != VERSION or urls != [URL]:
        raise ValueError("pinned URL does not match official release metadata")
    archive = ARTIFACTS / "chrome-mac-arm64.zip"
    if not archive.exists():
        partial = archive.with_suffix(".partial")
        try:
            deadline = time.monotonic() + 300
            total = 0
            with urllib.request.urlopen(URL, timeout=30) as source, partial.open("xb") as out:
                if source.url != URL:
                    raise ValueError("unexpected browser-artifact redirect")
                while chunk := source.read(1024 * 1024):
                    total += len(chunk)
                    if total > 1024**3 or time.monotonic() > deadline:
                        raise ValueError("download bound exceeded")
                    out.write(chunk)
            partial.replace(archive)
        finally:
            partial.unlink(missing_ok=True)
    base = ARTIFACTS / VERSION
    if not base.exists():
        with tempfile.TemporaryDirectory(prefix="extract-", dir=ARTIFACTS) as temporary:
            stage = Path(temporary)
            extract(archive, stage)
            verify_application(stage)
            stage.rename(base)
    verified = verify_application(base)
    result = {"version": VERSION, "url": URL, "metadata_url": METADATA,
              "official_metadata": metadata, "archive_sha256": sha256(archive),
              "verified_at_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
              **verified}
    (ARTIFACTS / "provenance.json").write_text(json.dumps(result, indent=2))
    print(json.dumps(result, indent=2))


class CDP:
    """One outstanding command, bounded framing and a bounded property inventory."""

    def __init__(self, reader, writer):
        self.reader, self.writer = reader, writer
        self.buffer = bytearray()
        self.serial = 0
        self.players = {}
        self.player_nodes = {}
        self.media_session = None
        self.decoder_epoch = 0
        self.expected_media_url = None
        self.fixture_loads = {}
        self.load_epoch = 0

    def message(self, deadline):
        while b"\0" not in self.buffer:
            remaining = deadline - time.monotonic()
            if remaining <= 0 or not select.select([self.reader], [], [], remaining)[0]:
                raise TimeoutError("CDP response deadline")
            chunk = self.reader.recv(65536)
            if not chunk:
                raise EOFError("browser control pipe closed")
            self.buffer.extend(chunk)
            if len(self.buffer) > 4 * 1024 * 1024:
                raise ValueError("CDP message bound exceeded")
        raw, _, rest = self.buffer.partition(b"\0")
        self.buffer = bytearray(rest)
        return json.loads(raw)

    def event(self, message):
        # Pinned Chromium 154.0.8037.57 domains/Media.pdl: playerCreated
        # carries the optional DOM.BackendNodeId. Missing association fails closed.
        # https://github.com/chromium/chromium/blob/154.0.8037.57/third_party/blink/public/devtools_protocol/domains/Media.pdl
        if message.get("sessionId") != self.media_session:
            return
        method = message.get("method")
        if method == "Media.playerCreated":
            player = message["params"]["player"]
            identity = player["playerId"]
            if identity not in self.player_nodes and len(self.player_nodes) >= 8:
                raise ValueError("unexpected player count")
            self.player_nodes[identity] = player.get("domNodeId")
        elif method == "Media.playerEventsAdded":
            # Actual CfT can omit optional domNodeId. Source-verified kLoad binds
            # its sole player to our sole unchanged element's exact currentSrc.
            # https://github.com/chromium/chromium/blob/154.0.8037.57/media/base/media_log_events.h
            identity = message["params"]["playerId"]
            if identity not in self.fixture_loads and len(self.fixture_loads) >= 8:
                raise ValueError("unexpected media event player count")
            for event in message["params"]["events"]:
                value = json.loads(event["value"])
                if value.get("event") == "kLoad":
                    self.fixture_loads[identity] = (self.expected_media_url is not None
                                                    and value.get("url") == self.expected_media_url)
                    self.load_epoch += 1
                elif value.get("event") == "kWebMediaPlayerDestroyed":
                    self.fixture_loads[identity] = False
                    self.load_epoch += 1
        elif method == "Media.playerPropertiesChanged":
            params = message["params"]
            player_id = params["playerId"]
            if player_id not in self.players and len(self.players) >= 8:
                raise ValueError("unexpected player count")
            player = self.players.setdefault(player_id, {})
            for prop in params["properties"]:
                if prop["name"] in PROPERTIES:
                    value = prop["value"]
                    if value is not None and not isinstance(value, str):
                        raise ValueError("invalid media property type")
                    if prop["name"] in ("kVideoDecoderName", "kIsPlatformVideoDecoder") and player.get(prop["name"]) != value:
                        self.decoder_epoch += 1
                    if value is None:
                        player.pop(prop["name"], None)
                    else:
                        player[prop["name"]] = value[:4096]

    def player_for_node(self, node):
        matches = [identity for identity, backend in self.player_nodes.items() if backend == node]
        if len(matches) == 1 and matches[0] in self.players:
            return matches[0]
        # Never use an unrelated historical hardware player to qualify a new
        # software player. Missing DOM metadata is admitted only for this fully
        # controlled single-element, single-player, exact-fixture source.
        if len(self.player_nodes) == len(self.players) == 1:
            identity, backend = next(iter(self.player_nodes.items()))
            if backend is None and identity in self.players and self.fixture_loads.get(identity):
                return identity
        raise ValueError("current video has no unique CDP player association")

    def call(self, method, params=None, session=None, timeout=10):
        self.serial += 1
        request = {"id": self.serial, "method": method, "params": params or {}}
        if session:
            request["sessionId"] = session
        self.writer.settimeout(timeout)
        self.writer.sendall(json.dumps(request).encode() + b"\0")
        deadline = time.monotonic() + timeout
        for _ in range(4096):
            message = self.message(deadline)
            self.event(message)
            if message.get("id") == self.serial:
                if "error" in message:
                    raise RuntimeError(f"CDP command failed: {method}")
                return message.get("result", {})
        raise ValueError("CDP event flood")

    def evaluate(self, session, expression, gesture=False):
        result = self.call("Runtime.evaluate", {"expression": expression,
                           "returnByValue": True, "awaitPromise": True,
                           "userGesture": gesture}, session)
        if "exceptionDetails" in result:
            raise RuntimeError("fixture JavaScript failed")
        return result["result"].get("value")


