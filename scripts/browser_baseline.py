def qualify(snapshot, players, width, height, player_id):
    if (not snapshot["identity_ok"] or not snapshot["in_view"]
            or snapshot["playback_rate"] != 1 or snapshot["paused"] or snapshot["muted"] or snapshot["volume"] <= 0
            or snapshot["error"] is not None or snapshot["visibility"] != "visible"
            or not snapshot["focused"] or snapshot["ready_state"] < 3
            or snapshot["width"] != 1920 or snapshot["height"] != 1080
            or snapshot["viewport_scale"] != 1
            or abs(snapshot["css_width"] * snapshot["dpr"] - width) > 0.1
            or abs(snapshot["css_height"] * snapshot["dpr"] - height) > 0.1):
        raise ValueError("visible/audible playback or geometry qualification failed")
    player = players.get(player_id, {})
    if (player.get("kVideoDecoderName") != "VideoToolboxVideoDecoder"
            or player.get("kIsPlatformVideoDecoder") != "true"):
        raise ValueError("actual VideoToolbox hardware decoder not established")



def qualify_interval(start, end, elapsed):
    if (end["time_origin"] != start["time_origin"]
            or end["changes"] != start["changes"]
            or end["duration"] != start["duration"]):
        raise ValueError("media/visibility/playback interval continuity failed")
    # W3C media-playback-quality: creationTime dates each quality snapshot;
    # it is not a player generation identifier. Loads are tracked by events.
    # https://w3c.github.io/media-playback-quality/
    counter_elapsed = (end["creation_time"] - start["creation_time"]) / 1000
    if not elapsed * 0.90 <= counter_elapsed <= elapsed * 1.10 + 0.1:
        raise ValueError("media snapshots do not span the recorded interval")
    frames = end["total_frames"] - start["total_frames"]
    dropped = end["dropped_frames"] - start["dropped_frames"]
    advanced = end["current_time"] - start["current_time"]
    if (frames < elapsed * 50 or dropped < 0 or dropped > frames
            or not elapsed * 0.90 <= advanced <= elapsed * 1.10 + 0.1):
        raise ValueError("frame counters or playback time lack continuous forward progress")
    return frames, dropped


def process_inventory(root, selected, table, cdp_processes):
    """Audit the same ps snapshot without storing executable paths or argv."""
    tree = measure.snapshot(root, False, set(), table)
    rows = [{"pid": pid, "parent_pid": row[0],
             "executable": "".join(c for c in Path(row[3]).name if c.isprintable())[:80],
             "attribution": "descendant_tree" if pid in tree else "new_vt_temporal"}
            for pid, row in sorted(selected.items())]
    cdp_ids = {item["id"] for item in cdp_processes}
    selected_ids = set(selected)
    return {"processes": rows, "cdp_not_in_ps_selection": sorted(cdp_ids - selected_ids),
            "ps_selection_not_in_cdp": sorted(selected_ids - cdp_ids),
            "note": "Endpoint snapshots are sequential, not atomic; exited/new processes may differ. "
                    "New VT service membership is temporal, not exclusive ownership proof."}

def launch_browser(binary, profile, log):
    send, child_read = socket.socketpair()
    child_write, receive = socket.socketpair()
    # Keep child descriptors above the destination slots 3/4 to avoid dup collisions.
    read_fd = fcntl.fcntl(child_read.fileno(), fcntl.F_DUPFD_CLOEXEC, 10)
    write_fd = fcntl.fcntl(child_write.fileno(), fcntl.F_DUPFD_CLOEXEC, 10)
    child_read.close()
    child_write.close()
    args = [str(binary), f"--user-data-dir={profile}", "--remote-debugging-pipe",
            "--no-first-run", "--no-default-browser-check", "--disable-background-networking",
            "--disable-component-update", "--disable-sync", "--disable-default-apps",
            "--disable-domain-reliability", "--metrics-recording-only", "--no-pings",
            "--use-mock-keychain", "--host-resolver-rules=MAP * ~NOTFOUND",
            "--window-size=1320,860", "about:blank"]
    try:
        process = subprocess.Popen([sys.executable, str(Path(__file__).resolve()),
                                    "_launch", str(read_fd), str(write_fd), *args],
                                   pass_fds=(read_fd, write_fd), start_new_session=True,
                                   stdout=log, stderr=log)
    except BaseException:
        send.close()
        receive.close()
        raise
    finally:
        os.close(read_fd)
        os.close(write_fd)
    return process, CDP(receive, send), args[1:]


def group_exists(pid):
    try:
        os.killpg(pid, 0)
        return True
    except ProcessLookupError:
        return False


def wait_group_gone(pid, timeout):
    deadline = time.monotonic() + timeout
    while group_exists(pid):
        if time.monotonic() >= deadline:
            return False
        time.sleep(0.05)
    return True


def stop_browser(process, cdp):
    outcome = {"forced_termination": False, "process_group_gone": False,
               "cleanup_errors": []}
    try:
        try:
            cdp.call("Browser.close", timeout=3)
        except (OSError, ValueError, RuntimeError, TimeoutError, EOFError):
            pass
        except BaseException as exc:
            outcome["cleanup_errors"].append(f"{type(exc).__name__}: {exc}")
        try:
            process.wait(timeout=10)
        except subprocess.TimeoutExpired:
            outcome["forced_termination"] = True
        # Parent exit is not child-group exit. Check again after SIGKILL, too.
        for termination in (signal.SIGTERM, signal.SIGKILL):
            if not group_exists(process.pid):
                break
            outcome["forced_termination"] = True
            try:
                os.killpg(process.pid, termination)
            except ProcessLookupError:
                pass
            try:
                process.wait(timeout=3)
            except subprocess.TimeoutExpired:
                pass
            if wait_group_gone(process.pid, 3):
                break
        process.wait(timeout=3)  # reap our direct child even after group shutdown
        outcome["process_group_gone"] = not group_exists(process.pid)
    except BaseException as exc:
        outcome["cleanup_errors"].append(f"{type(exc).__name__}: {exc}")
    finally:
        for stream in (cdp.reader, cdp.writer):
            try:
                stream.close()
            except BaseException as exc:
                outcome["cleanup_errors"].append(f"{type(exc).__name__}: {exc}")
        outcome["exit_code"] = process.returncode
    return outcome


def finalize(run_dir, result, process, cdp):
    """Always preserve measurements; uncertain child ownership retains its profile."""
    outcome = {"process_group_gone": process is None, "forced_termination": False,
               "cleanup_errors": [], "exit_code": None}
    if process is not None:
        try:
            outcome.update(stop_browser(process, cdp))
        except BaseException as exc:
            outcome["cleanup_errors"].append(f"{type(exc).__name__}: {exc}")
    result.update(outcome)
    if (not outcome["process_group_gone"] or outcome["forced_termination"]
            or outcome["cleanup_errors"] or (process is not None and outcome["exit_code"] != 0)):
        result["status"] = "incomplete"
    result["profile_retained_for_live_or_unknown_group"] = not outcome["process_group_gone"]
    # Persist before optional filesystem cleanup so a removal error loses no data.
    evidence = run_dir / "result.json"
    evidence.write_text(json.dumps(result, indent=2))
    if outcome["process_group_gone"]:
        try:
            profile = run_dir / "profile"
            if profile.exists():
                shutil.rmtree(profile)
            (run_dir / "clip.mp4").unlink(missing_ok=True)
        except BaseException as exc:
            result["cleanup_errors"].append(f"{type(exc).__name__}: {exc}")
            result["status"] = "incomplete"
    evidence.write_text(json.dumps(result, indent=2))


def run(args):
    if not (1 <= args.seconds <= 60 and 0 <= args.warmup <= 15):
        raise ValueError("run duration must fit the bounded 90-second fixture")
    if not (1 <= args.width <= 2560 and 1 <= args.height <= 1600):
        raise ValueError("invalid fixture geometry")
    base = ARTIFACTS / VERSION
    verified = verify_application(base)
    provenance = json.loads((ARTIFACTS / "provenance.json").read_text())
    if verified["executable_sha256"] != provenance["executable_sha256"]:
        raise ValueError("prepared browser changed")
    clip = ROOT / "artifacts/local-1080p60.mp4"
    if not clip.is_file() or clip.is_symlink():
        raise ValueError("generate the local fixture first; symlinks are not admitted")
    run_dir = Path(tempfile.mkdtemp(prefix="run-", dir=ARTIFACTS))
    run_dir.chmod(0o700)
    # A hard link admits only the owned generated fixture, not arbitrary personal media.
    os.link(clip, run_dir / "clip.mp4")
    (run_dir / "index.html").write_text("""<!doctype html><meta charset=utf-8>
<meta http-equiv=Content-Security-Policy content="default-src 'none'; media-src 'self'; style-src 'unsafe-inline'">
<title>Serein local browser baseline</title><style>html,body{margin:0;background:#161616}
video{display:block;object-fit:contain}</style><video preload=none playsinline></video>""")
    result = {"browser": provenance, "harness_sha256": sha256(Path(__file__)),
              "clip_sha256": sha256(clip), "warmup_seconds": args.warmup,
              "physical_video_width": args.width, "physical_video_height": args.height,
              "include_new_vt_services": args.include_new_vt_services,
              "status": "incomplete", "samples": []}
    baseline = set(measure.process_table())
    process, cdp = None, None
    error = None
    with (run_dir / "browser.log").open("w") as log:
        try:
            process, cdp, flags = launch_browser(base / EXE_REL, run_dir / "profile", log)
            result["flags"] = [f if not f.startswith("--user-data-dir=") else
                               "--user-data-dir=<isolated-run-profile>" for f in flags]
            result["runtime_version"] = cdp.call("Browser.getVersion")
            target_deadline = time.monotonic() + 10
            while True:
                targets = cdp.call("Target.getTargets")["targetInfos"]
                target = next((t for t in targets if t["type"] == "page"), None)
                if target is not None:
                    break
                if time.monotonic() >= target_deadline:
                    raise TimeoutError("native browser page startup deadline")
                time.sleep(0.05)
            session = cdp.call("Target.attachToTarget", {"targetId": target["targetId"],
                                                        "flatten": True})["sessionId"]
            cdp.call("Page.enable", session=session)
            cdp.call("DOM.enable", session=session)
            cdp.media_session = session
            cdp.expected_media_url = (run_dir / "clip.mp4").as_uri()
            cdp.call("Media.enable", session=session)
            cdp.call("Network.enable", session=session)
            cdp.call("Network.setBlockedURLs", {"urls": ["http://*", "https://*"]}, session)
            cdp.call("Page.navigate", {"url": (run_dir / "index.html").as_uri()}, session)
            deadline = time.monotonic() + 10
            while not cdp.evaluate(session, "document.querySelector('video') !== null"):
                if time.monotonic() > deadline:
                    raise TimeoutError("fixture navigation deadline")
                time.sleep(0.05)
            document = cdp.call("DOM.getDocument", session=session)["root"]["nodeId"]
            node = cdp.call("DOM.querySelector", {"nodeId": document, "selector": "video"}, session)["nodeId"]
            backend_node = cdp.call("DOM.describeNode", {"nodeId": node}, session)["node"]["backendNodeId"]
            cdp.evaluate(session, """(() => {window.baselineVideo=document.querySelector('video');
window.baselineChanges=0; const changed=()=>{window.baselineChanges++};
for(const event of ['pause','seeking','emptied','loadedmetadata','ratechange','volumechange'])
 baselineVideo.addEventListener(event,changed);
for(const event of ['blur','resize']) window.addEventListener(event,changed);
document.addEventListener('visibilitychange',changed);})()""")
            cdp.call("Page.bringToFront", session=session)
            cdp.evaluate(session, f"""(() => {{const v=document.querySelector('video');
v.style.width=({args.width}/devicePixelRatio)+'px';
v.style.height=({args.height}/devicePixelRatio)+'px';v.src='clip.mp4';return v.play();}})()""", True)
            time.sleep(args.warmup)
            start_media = cdp.evaluate(session, SNAPSHOT_JS)
            result["media_start"] = start_media
            result["decoder_start"] = list(cdp.players.values())
            result["player_nodes"] = dict(cdp.player_nodes)
            result["video_backend_node"] = backend_node
            selected_player = cdp.player_for_node(backend_node)
            decoder_epoch = cdp.decoder_epoch
            load_epoch = cdp.load_epoch
            result["decoder_association"] = "backend_dom_node" if cdp.player_nodes[selected_player] is not None else "sole_player_exact_fixture_load"
            result["selected_player"] = selected_player
            qualify(start_media, cdp.players, args.width, args.height, selected_player)
            media_start_clock = time.monotonic()
            result["cdp_processes_start"] = cdp.call("SystemInfo.getProcessInfo")["processInfo"]
            result["native_window"] = cdp.call("Browser.getWindowForTarget",
                                               {"targetId": target["targetId"]})
            previous_table = measure.process_table()
            previous = measure.snapshot(process.pid, args.include_new_vt_services,
                                        baseline, previous_table)
            result["process_inventory_start"] = process_inventory(
                process.pid, previous, previous_table, result["cdp_processes_start"])
            result["measurement_start_utc"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
            last = start = time.monotonic()
            for index in range(args.seconds):
                time.sleep(max(0, start + index + 1 - time.monotonic()))
                now = time.monotonic()
                table = measure.process_table()
                current = measure.snapshot(process.pid, args.include_new_vt_services, baseline, table)
                if process.poll() is not None:
                    raise RuntimeError("browser exited during measurement")
                result["samples"].append({"rss_mib": sum(v[1] for v in current.values()) / 1024,
                    "cpu_one_core_percent": 100 * measure.cpu_delta(current, previous) / (now-last),
                    "processes": len(current), "elapsed_after_warmup_seconds": now-start,
                    **measure.host_other_cpu(table, previous_table, set(current), now-last)})
                previous, previous_table, last = current, table, now
            end_media = cdp.evaluate(session, SNAPSHOT_JS)
            result["media_end"] = end_media
            result["decoder_end"] = list(cdp.players.values())
            media_elapsed = time.monotonic() - media_start_clock
            if (cdp.player_for_node(backend_node) != selected_player
                    or cdp.decoder_epoch != decoder_epoch or cdp.load_epoch != load_epoch):
                raise ValueError("selected native decoder changed during measurement")
            qualify(end_media, cdp.players, args.width, args.height, selected_player)
            result["cdp_processes_end"] = cdp.call("SystemInfo.getProcessInfo")["processInfo"]
            result["process_inventory_end"] = process_inventory(
                process.pid, previous, previous_table, result["cdp_processes_end"])
            result["media_counter_interval_seconds"] = media_elapsed
            result["frame_delta"], result["dropped_frame_delta"] = qualify_interval(start_media, end_media, media_elapsed)
            for name in ("rss_mib", "cpu_one_core_percent", "host_other_cpu_one_core_percent"):
                result[name] = measure.statistics([row[name] for row in result["samples"]])
            result["status"] = "completed_not_automatically_qualified"
        except BaseException as exc:
            error = exc
            result["failure"] = f"{type(exc).__name__}: {exc}"
        finally:
            result["notes"] = ("RSS can double-count shared pages; GPU memory is not added. "
                "Short-lived/reparented helpers can escape ps attribution; compare CDP PID inventory. "
                "New VT services are temporally attributed, not proven exclusively owned. "
                "Host-other CPU includes harness/system work and is never charged to the browser. "
                "CSS physical geometry does not establish compositor allocation size or scanout. "
                "DOM visibility/focus and transition events do not prove native unoccluded scanout, "
                "display wake state or audible device output. Video counters measure submitted/dropped "
                "frames, not compositor presentation. No continuous GPU or audio-route probe is made. "
                "Decoder evidence, audible output, display state, dropped-frame gate and "
                "foreign-work audit require review before comparison. Background flags and page URL "
                "blocking are not comprehensive whole-browser egress verification.")
            finalize(run_dir, result, process, cdp)
    print(run_dir / "result.json")
    if error:
        raise error
    if result["status"] == "incomplete":
        raise RuntimeError("browser did not exit cleanly")


def main():
    if len(sys.argv) > 1 and sys.argv[1] == "_launch":
        # This process immediately becomes Chrome; no separate persistent driver process.
        read_fd, write_fd = map(int, sys.argv[2:4])
        os.dup2(read_fd, 3)
        os.dup2(write_fd, 4)
        os.close(read_fd)
        os.close(write_fd)
        os.execv(sys.argv[4], sys.argv[4:])
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("prepare")
    run_parser = sub.add_parser("run")
    run_parser.add_argument("--warmup", type=int, default=10)
    run_parser.add_argument("--seconds", type=int, default=60)
    run_parser.add_argument("--width", type=int, default=1384)
    run_parser.add_argument("--height", type=int, default=778)
    run_parser.add_argument("--include-new-vt-services", action="store_true")
    args = parser.parse_args()
    if args.command == "prepare":
        prepare()
    else:
        def terminated(signum, _frame):
            raise InterruptedError(f"harness received signal {signum}")
        previous = signal.signal(signal.SIGTERM, terminated)
        try:
            run(args)
        finally:
            signal.signal(signal.SIGTERM, previous)


if __name__ == "__main__":
    main()
